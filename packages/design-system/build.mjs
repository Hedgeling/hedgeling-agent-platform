import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
export async function buildBrand(name = "hedgeling", output = root) {
  if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error("Invalid brand name");
  const directory = path.join(root, "brands", name);
  const tokens = JSON.parse(await fs.readFile(path.join(directory, "tokens.json"), "utf8"));
  const brand = JSON.parse(await fs.readFile(path.join(directory, "brand.json"), "utf8"));
  if (tokens.version !== 1 || brand.version !== 1 || brand.id !== name) throw new Error("Unsupported brand contract");
  const declarations = (values) => Object.entries(values).map(([key, value]) => {
    if (!/^[a-z][a-z0-9-]*$/.test(key) || typeof value !== "string" || /[{};<>]|url\s*\(/i.test(value)) throw new Error(`Invalid token: ${key}`);
    return `  --${key}: ${value};`;
  }).join("\n");
  for (const key of ["background-base", "background-pane", "text-main", "text-muted", "font-ui", "agent-surface", "agent-overlay"]) {
    if (!tokens.light[key]) throw new Error(`Missing semantic token: ${key}`);
  }
  const publicBrand = { ...brand };
  for (const key of ["logo", "mascot"]) {
    if (!/^[a-z0-9-]+\.(png|svg|webp|jpeg)$/.test(brand[key])) throw new Error("Invalid brand asset");
    await fs.access(path.join(directory, "assets", brand[key]));
    publicBrand[key] = `/design-system/assets/${brand[key]}`;
  }
  await fs.mkdir(output, { recursive: true });
  await fs.cp(path.join(directory, "assets"), path.join(output, "assets"), { recursive: true });
  await fs.writeFile(path.join(output, "theme.css"), `/* Generated by packages/design-system/build.mjs. Edit brands/${name}/tokens.json. */\n:root {\n  color-scheme: light;\n${declarations(tokens.light)}\n}\n[data-theme="dark"], .theme-dark {\n  color-scheme: dark;\n${declarations(tokens.dark)}\n}\n`);
  await fs.writeFile(path.join(output, "brand.json"), JSON.stringify(publicBrand, null, 2) + "\n");
  const moduleBrand = { version: brand.version, id: brand.id, productName: brand.productName, agentName: brand.agentName };
  await fs.writeFile(path.join(output, "brand.js"), `// Generated brand assets for bundled applications.\nexport const brand = { ...${JSON.stringify(moduleBrand)}, logo: new URL(${JSON.stringify(`./assets/${brand.logo}`)}, import.meta.url).href, mascot: new URL(${JSON.stringify(`./assets/${brand.mascot}`)}, import.meta.url).href };\n`);
  await fs.writeFile(path.join(output, "tokens.json"), JSON.stringify(tokens, null, 2) + "\n");
  if (output === root) await fs.writeFile(path.join(root, "..", "web-console", "src", "public", "tokens.json"), JSON.stringify(tokens, null, 2) + "\n");
  return publicBrand;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const brand = await buildBrand(process.argv[2] || process.env.HEDGELING_BRAND || "hedgeling");
  console.log(`Built ${brand.productName} design system`);
}
