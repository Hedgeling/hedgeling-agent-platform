import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { localConsole, eventually } from '../test-support/local-console.mjs';
import { extractionEngine, seedExtractionProject } from '../test-support/extraction-engine.mjs';
test('config/tune/save/re-extract uses scoped human approvals, pinned source, durable settings and separate import', {skip:process.env.HEDGELING_REQUIRE_AGENT_TEST_DATABASE!=='true'}, async t => {
  const engine=await extractionEngine();t.after(engine.close);
  const app=await localConsole(process.env.TEST_DATABASE_URL,engine.env);t.after(app.close);
  const {request,database}=app,p=await seedExtractionProject(database),controllerId=crypto.randomUUID();
  const input={projectSlug:p.slug,connectionId:'test-source',ref:'main',scanRoots:['src'],configPath:'.hedgeling/extract.config.json'};
  const call=async(name,input)=>{const r=await request('/api/actions/'+name,input);assert.equal(r.status,200,JSON.stringify(r.body));return r.body.result;};
  const confirm=proposal=>request(`/api/agent/proposals/${proposal.id}/confirm`,{controllerId,fingerprint:proposal.fingerprint});
  const config=await call('extraction.config',{...input,scanRoots:undefined});
  assert.deepEqual(config.effectiveSettings,{excludeFields:['telemetryLabel']});assert.equal(config.repository.commitSha,'a'.repeat(40));
  for(const configPath of ['../.hedgeling/extract.config.json','config.js','other/.hedgeling/extract.config.json']) assert([400,403].includes((await request('/api/actions/extraction.config',{...input,scanRoots:undefined,configPath})).status));
  assert.equal((await request('/api/actions/extraction.config',{...input,scanRoots:undefined,connectionId:'wrong'})).status,403);
  const run=(await request('/api/agent/runs',{organizationId:p.org,controllerId})).body.run;
  await request(`/api/agent/runs/${run.id}/messages`,{controllerId,text:`Tune extraction for project "${p.slug}" at "main" in "src".`});
  const ready=await eventually(()=>request(`/api/agent/runs/${run.id}`),r=>r.body.run?.status==='awaiting_confirmation',20000);
  const proposal=ready.body.proposals[0];assert.equal(proposal.preview.action,'extraction.tune');assert.equal(engine.jobs.size,0);
  assert.equal(proposal.preview.fields.ref,'a'.repeat(40));
  const started=await confirm(proposal);assert.equal(started.status,200,JSON.stringify(started.body));
  const tuningId=started.body.result.extraction.id, selection={projectSlug:p.slug,extractionId:tuningId};
  assert.equal((await request('/api/actions/extraction.tuning.apply',selection)).status,409);
  engine.control.complete=true;
  const report=await call('extraction.get',selection);assert.equal(report.tuning.acceptedEdits[0].value,'trackDebug');
  assert.equal((await request('/api/actions/extraction.import',selection)).status,409);
  const save=(await call('extraction.tuning.apply',selection)).proposal;
  assert.equal((await database.query('select count(*)::int n from extraction_settings')).rows[0].n,0);
  assert.equal((await request(`/api/agent/proposals/${save.id}/confirm`,{controllerId,fingerprint:'wrong'})).status,409);
  const results=await Promise.all([confirm(save),confirm(save)]);
  for(const r of results)assert.equal(r.status,200,JSON.stringify(r.body));
  assert.equal(results.filter(r=>r.body.replayed).length,1);assert.equal(engine.jobs.size,2);
  const extractionId=results[0].body.result.extraction.id;
  assert.equal(engine.jobs.get(extractionId).ref,'a'.repeat(40));assert.deepEqual(engine.jobs.get(extractionId).settings.excludeCallees,['trackDebug']);
  assert.equal((await database.query('select count(*)::int n from source_strings')).rows[0].n,0);
  const saved=await call('extraction.settings',{projectSlug:p.slug,connectionId:'test-source'});
  assert.deepEqual(JSON.parse(saved.download.content).scanRoots,['src']);assert.deepEqual(saved.saved.settings.excludeCallees,['trackDebug']);
  const next=(await call('extraction.start',{projectSlug:p.slug,connectionId:'test-source',ref:'main',scanRoots:['src']})).proposal;
  assert.deepEqual(next.preview.fields.settings.excludeCallees,['trackDebug']);
  const importPlan=(await call('extraction.import',{projectSlug:p.slug,extractionId})).proposal;
  assert.equal((await confirm(importPlan)).status,200);assert.equal((await database.query('select count(*)::int n from source_strings')).rows[0].n,2);
  // A separate tune cannot overwrite settings that changed after its preview.
  const again=(await call('extraction.tune',input)).proposal,againResult=await confirm(again);
  assert.equal(againResult.status,200,JSON.stringify(againResult.body));
  await database.query("update extraction_settings set settings='{}',updated_at=now() where project_id=$1",[p.id]);
  assert.equal((await request('/api/actions/extraction.tuning.apply',{projectSlug:p.slug,extractionId:againResult.body.result.extraction.id})).status,409);
  assert.equal((await database.query("select count(*)::int n from audit_events where action='extraction.tuning.apply.confirmed'")).rows[0].n,1);
  const userId=(await request('/api/me')).body.auth.user.id;
  await database.query('update role_assignments set revoked_at=now() where principal_id=$1',[userId]);
  assert.equal((await confirm(save)).status,403);
  assert.equal((await request('/api/actions/extraction.settings',{projectSlug:p.slug,connectionId:'test-source'})).status,403);
});
