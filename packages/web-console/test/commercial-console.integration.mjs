test("trial expiry gates chat but preserves history and manual access; paid plans include chat", options, async (t) => {
  const app = await localConsole(process.env.TEST_DATABASE_URL); t.after(app.close);
  const { request, database } = app;
  const org = (await request("/api/agent/config")).body.organizations[0].id;
  const account = (await database.query("insert into billing_accounts(organization_id) values($1) returning id", [org])).rows[0].id;
  await database.query("insert into subscriptions(billing_account_id,plan_id,state,current_period_start,current_period_end) select $1,id,'trialing',now(),now()+interval '14 days' from product_plans where key='self-service-trial-v1'", [account]);
  const controllerId = crypto.randomUUID();
  const run = (await request("/api/agent/runs", { organizationId: org, controllerId })).body.run;
  assert.ok(run);
  const before = await request(`/api/access/organizations/${org}/billing-summary`);
  assert.equal(before.status, 200); assert.equal(before.body.chat.allowed, true); assert.equal(before.body.ai.includedCredits, 25000);
  assert.equal(before.body.payment.mode, "unconfigured");
  await database.query("update subscriptions set current_period_end=now()-interval '1 second' where billing_account_id=$1", [account]);
  const config = (await request("/api/agent/config")).body;
  assert.equal(config.organizations[0].chat.allowed, false); assert.equal(config.organizations[0].chat.reason, "trial_expired");
  assert.equal((await request("/api/agent/runs", { organizationId: org, controllerId })).status, 402);
  assert.equal((await request(`/api/agent/runs/${run.id}/messages`, { controllerId, text: "Hello" })).status, 402);
  assert.equal((await request(`/api/agent/runs/${run.id}/continue`, { controllerId })).status, 402);
  assert.equal((await request(`/api/agent/runs/${run.id}/pause`, {})).status, 200);
  assert.equal((await request(`/api/agent/runs/${run.id}/resume`, { controllerId })).status, 402);
  assert.equal((await request(`/api/agent/runs/${run.id}`)).status, 200);
  assert.equal((await request("/api/actions/projects.list", { organizationId: org })).status, 200);
  assert.equal((await database.query("select count(*)::int as n from agent_model_usage")).rows[0].n, 0);
  await database.query("update subscriptions set plan_id=(select id from product_plans where key='starter-v1'),state='active',current_period_end=now()+interval '1 month' where billing_account_id=$1", [account]);
  assert.equal((await request(`/api/agent/runs/${run.id}/resume`, { controllerId })).status, 200);
  assert.equal((await request(`/api/access/organizations/${org}/billing-summary`)).body.chat.included, true);
  await database.query("update subscriptions set plan_id=(select id from product_plans where key='business-v1') where billing_account_id=$1", [account]);
  const competingCaps = await Promise.all([1000, 2000].map((amountMinor) => fetch(`${app.origin}/api/access/organizations/${org}/commercial-settings/ai-credit-cap`, {
    method: "PUT", headers: { origin: app.origin, cookie: app.cookie, "content-type": "application/json" }, body: JSON.stringify({ amountMinor, expectedAmountMinor: "0" }),
  }).then((response) => response.status)));
  assert.deepEqual(competingCaps.sort(), [200, 409]);
});

test("organization key changes require exact human previews, isolate secrets and tenants, and allow removal after expiry", options, async (t) => {
  const app = await localConsole(process.env.TEST_DATABASE_URL, { HEDGELING_AI_KEY_ID: "test", HEDGELING_AI_KEYRING: JSON.stringify({ test: crypto.randomBytes(32).toString("base64") }) }); t.after(app.close);
  const { request, database } = app;
  const org = (await request("/api/agent/config")).body.organizations[0].id;
  const base = `/api/access/organizations/${org}/ai-providers`;
  const user = (await request("/api/me")).body.auth.user.id;
  const account = (await database.query("insert into billing_accounts(organization_id) values($1) returning id", [org])).rows[0].id;
  await database.query("insert into subscriptions(billing_account_id,plan_id,state,current_period_start,current_period_end) select $1,id,'active',now(),now()+interval '1 month' from product_plans where key='starter-v1'", [account]);
  const key = "synthetic-Gemini-key-for-tests-only-1234";
  const proposed = await request(`${base}/preview`, { action: "connect", key });
  assert.equal(proposed.status, 200, JSON.stringify(proposed.body));
  const p = proposed.body.proposal;
  assert.ok(!JSON.stringify(p).includes(key)); assert.equal(p.preview.after, "••••1234");
  assert.equal((await database.query("select count(*)::int as n from organization_ai_credentials")).rows[0].n, 0);
  const pending = (await database.query("select payload from organization_ai_proposals where id=$1", [p.id])).rows[0].payload;
  assert.ok(!JSON.stringify(pending).includes(key));
  const confirm = (id) => request(`${base}/proposals/${id}/confirm`, {});
  assert.equal((await confirm(p.id)).status, 200); assert.equal((await confirm(p.id)).body.replayed, true);
  const saved = await request(base); assert.equal(saved.body.eligible, true); assert.equal(saved.body.translationMode, "managed");
  assert.ok(!JSON.stringify(saved.body).includes(key)); assert.equal(saved.body.credential.maskedKey, "••••1234");
  assert.deepEqual((await database.query("select payload from organization_ai_proposals where id=$1", [p.id])).rows[0].payload, {});
  const a = (await request(`${base}/preview`, { action: "translation_mode", mode: "byok" })).body.proposal;
  const b = (await request(`${base}/preview`, { action: "connect", key: `${key}5678` })).body.proposal;
  assert.equal((await confirm(a.id)).status, 200); assert.equal((await confirm(b.id)).status, 409);
  const rejected = (await request(`${base}/preview`, { action: "connect", key })).body.proposal;
  assert.equal((await request(`${base}/proposals/${rejected.id}/reject`, {})).status, 200);
  assert.equal((await confirm(rejected.id)).status, 409);
  const expiring = (await request(`${base}/preview`, { action: "connect", key })).body.proposal;
  await database.query("update organization_ai_proposals set expires_at=now()-interval '1 second' where id=$1", [expiring.id]);
  assert.equal((await confirm(expiring.id)).status, 409);
  assert.deepEqual((await database.query("select payload from organization_ai_proposals where id=$1", [expiring.id])).rows[0].payload, {});
  const foreign = (await database.query("insert into organizations(name,slug) values('Unrelated','unrelated-keys') returning id")).rows[0].id;
  assert.equal((await request(`/api/access/organizations/${foreign}/ai-providers`)).status, 403);
  assert.equal((await request(`/api/access/organizations/${foreign}/billing-summary`)).status, 403);
  const service = (await database.query("insert into service_accounts(organization_id,name) values($1,'Machine') returning id", [org])).rows[0].id;
  const credential = createServiceCredential();
  await database.query("insert into service_account_credentials(service_account_id,token_prefix,token_digest) values($1,$2,$3)", [service, credential.prefix, credential.digest]);
  await database.query("insert into role_assignments(principal_type,principal_id,role_id,scope_type,scope_id) select 'service_account',$1,id,'organization',$2 from roles where key='organization_owner' and organization_id is null", [service, org]);
  assert.equal((await request(`${base}/preview`, { action: "connect", key }, { cookie: "", authorization: `Bearer ${credential.token}` })).status, 403);
  assert.equal((await request(`/api/access/organizations/${org}/billing/checkout`, { priceKey: "ignored" }, { cookie: "", authorization: `Bearer ${credential.token}` })).status, 403);
  const denied = (await request(`${base}/preview`, { action: "translation_mode", mode: "managed" })).body.proposal;
  await database.query("update role_assignments set revoked_at=now() where principal_type='user' and principal_id=$1 and scope_id=$2", [user, org]);
  assert.equal((await confirm(denied.id)).status, 403);
  await database.query("update role_assignments set revoked_at=null where principal_type='user' and principal_id=$1 and scope_id=$2", [user, org]);
  await database.query("update subscriptions set state='unpaid' where billing_account_id=$1", [account]);
  assert.equal((await request(`${base}/preview`, { action: "connect", key })).status, 402);
  const removal = (await request(`${base}/preview`, { action: "remove" })).body.proposal;
  assert.equal((await confirm(removal.id)).status, 200);
  const removed = (await request(base)).body; assert.equal(removed.credential, null); assert.equal(removed.translationMode, "byok");
  const audit = (await database.query("select before_state,after_state,metadata from audit_events where action like 'ai_provider.%'")).rows;
  assert.equal(audit.length, 3); assert.ok(!JSON.stringify(audit).includes(key));
});


test("Meta and Gemini keys coexist; confirmed Meta routing uses context and records BYOK without managed fallback", options, async (t) => {
  const meta = await metaProvider(); t.after(meta.close);
  const app = await localConsole(process.env.TEST_DATABASE_URL, { ...meta.env,
    HEDGELING_AI_KEY_ID: "test", HEDGELING_AI_KEYRING: JSON.stringify({ test: crypto.randomBytes(32).toString("base64") }) }); t.after(app.close);
  const { request, database } = app;
  const org = (await request("/api/agent/config")).body.organizations[0].id;
  const base = `/api/access/organizations/${org}/ai-providers`;
  const account = (await database.query("insert into billing_accounts(organization_id) values($1) returning id", [org])).rows[0].id;
  await database.query("insert into subscriptions(billing_account_id,plan_id,state,current_period_start,current_period_end) select $1,id,'active',now(),now()+interval '1 month' from product_plans where key='business-v1'", [account]);
  const change = async payload => {
    const preview = await request(`${base}/preview`, payload);
    assert.equal(preview.status, 200, JSON.stringify(preview.body));
    const result = await request(`${base}/proposals/${preview.body.proposal.id}/confirm`, {});
    assert.equal(result.status, 200, JSON.stringify(result.body)); return preview.body.proposal;
  };
  const geminiKey = "synthetic-Gemini-key-1234", metaKey = "synthetic.Meta.key/with+bearer-chars=5678";
  await change({ action: "connect", key: geminiKey });
  await change({ action: "connect", provider: "meta", key: metaKey });
  const settings = (await request(base)).body;
  assert.equal(settings.translationMode, "managed"); assert.equal(settings.providers.meta.ready, true);
  assert.deepEqual(Object.keys(settings.credentials).sort(), ["gemini", "meta"]);
  assert.equal(settings.credential.maskedKey, "••••1234"); assert.equal(settings.credentials.meta.maskedKey, "••••5678");
  assert.deepEqual(settings.chat, { mode: "managed", included: true });
  assert.ok(!JSON.stringify(settings).includes(metaKey));
  assert.equal((await request(`${base}/preview`, { action: "connect", provider: "unknown", key: metaKey })).status, 400);
  assert.equal((await request(`${base}/preview`, { action: "connect", provider: "meta", key: metaKey + "\nheader" })).status, 400);
  const foreign = (await database.query("insert into organizations(name,slug) values('Foreign','foreign-meta') returning id")).rows[0].id;
  assert.equal((await request(`/api/access/organizations/${foreign}/ai-providers/test`, { provider: "meta" })).status, 403);
  assert.equal((await request(`${base}/test`, { provider: "meta" })).status, 200);
  assert.equal(meta.calls.length, 1); assert.equal(meta.calls[0].method, "GET");
  assert.equal(meta.calls[0].authorization, `Bearer ${metaKey}`); assert.equal(meta.calls[0].path, "/v1/models/test-meta-model");
  const tested = (await request(base)).body;
  assert.ok(tested.credentials.meta.validatedAt); assert.equal(tested.credentials.gemini.validatedAt, null);
  await change({ action: "translation_mode", mode: "byok", provider: "gemini" });
  await change({ action: "translation_mode", mode: "byok", provider: "meta" });
  const project = (await database.query("select id from projects where slug='hedgeling-local'")).rows[0].id;
  const source = (await database.query("insert into source_strings(project_id,source_hash,source_text,purpose) values($1,'meta-source','Hello {name}','Warm greeting on the welcome screen') returning id", [project])).rows[0].id;
  await database.query("insert into prompts(project_id,key,label,body,active) values($1,'library-active','Voice','Use warm library guidance',true),($1,'library-inactive','Unused','INACTIVE_PROMPT_MARKER',false)", [project]);
  await database.query("insert into personas(project_id,locale,body) values($1,'fr','{\"tone\":\"Library voice in French\"}')", [project]);
  await database.query("insert into glossary_terms(project_id,term,locale,translation,active) values($1,'Hello','fr','Bonjour',true),($1,'Hello','fr','INACTIVE_TERM_MARKER',false)", [project]);
  const revise = `/api/translations/${source}/fr/revise`;
  const result = await request(revise, { instruction: "Keep it welcoming" }, { "idempotency-key": "meta-byok-revision-0001" });
  assert.equal(result.status, 200, JSON.stringify(result.body));
  assert.equal(result.body.translation.text, "Bonjour {name}"); assert.equal(result.body.translation.provider, "meta");
  assert.equal(result.body.translation.model, "test-meta-model"); assert.equal(result.body.translation.source, "mt");
  assert.equal(result.body.aiCredits, 0); assert.equal(result.body.billingCategory, "organization_provider");
  assert.equal(meta.calls[1].authorization, `Bearer ${metaKey}`); assert.equal(meta.calls[1].body.store, false);
  assert.ok(meta.calls[1].body.input.includes("Warm greeting"));
  assert.ok(meta.calls[1].body.input.includes("Use warm library guidance"));
  assert.ok(meta.calls[1].body.input.includes("Library voice in French"));
  assert.ok(!meta.calls[1].body.input.includes("INACTIVE_PROMPT_MARKER"));
  assert.ok(!meta.calls[1].body.input.includes("INACTIVE_TERM_MARKER"));
  const usage = (await database.query("select provider,metadata from usage_events where operation='ai_translation_revision' and outcome='succeeded'")).rows[0];
  assert.equal(usage.provider, "meta"); assert.equal(usage.metadata.aiCredits.quantity, 0);
  const revision = (await database.query("select revision_source,prompt_snapshot from translation_revisions where source_string_id=$1", [source])).rows[0];
  assert.equal(revision.revision_source, "mt"); assert.equal(revision.prompt_snapshot.provider, "meta");
  assert.equal(revision.prompt_snapshot.libraryVersions.prompts.length, 1);
  assert.equal(revision.prompt_snapshot.libraryVersions.persona.length, 1);
  assert.equal(revision.prompt_snapshot.libraryVersions.glossary.length, 1);
  assert.match(revision.prompt_snapshot.libraryVersions.glossary[0].contentHash, /^[a-f0-9]{64}$/);
  meta.control.fail = true;
  const failed = await request(revise, { instruction: "Try again" });
  assert.equal(failed.status, 502); assert.ok(!JSON.stringify(failed.body).includes("private upstream detail"));
  assert.equal(meta.calls.length, 3);
  meta.control.fail = false; meta.control.text = "Bonjour";
  const invalid = await request(revise, { instruction: "Preserve placeholders" });
  assert.equal(invalid.status, 502); assert.match(invalid.body.error, /Meta revision rejected/);
  assert.equal((await database.query("select text from translations where source_string_id=$1", [source])).rows[0].text, "Bonjour {name}");
  const removal = await change({ action: "remove", provider: "meta" });
  assert.match(removal.preview.effect, /will stop/);
  const after = (await request(base)).body;
  assert.equal(after.translationProvider, "meta"); assert.equal(after.translationMode, "byok");
  assert.ok(after.credentials.gemini); assert.equal(after.credentials.meta, undefined);
  assert.equal((await request(revise, { instruction: "Still paused" })).status, 409);
  assert.equal(meta.calls.length, 5);
  const audit = (await database.query("select before_state,after_state,metadata from audit_events where action like 'ai_provider.%'")).rows;
  assert.ok(!JSON.stringify(audit).includes(metaKey));
});
