import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { setupTranslationJobs as setup } from '../test-support/translation-jobs.mjs';
import { eventually } from '../test-support/local-console.mjs';
const options = { skip: process.env.HEDGELING_REQUIRE_AGENT_TEST_DATABASE !== 'true' };
const flow = async a => {
  const r = await a.request('/api/actions/localization_flow.get', { projectSlug: a.project.slug });
  assert.equal(r.status, 200, JSON.stringify(r.body)); return r.body.result.flow;
};
const configure = async (a, changes) => a.preview('localization_flow.configure', { projectSlug: a.project.slug, revision: (await flow(a)).choices.revision, ...changes });
const draft = async (a, preset) => (await a.confirm(await a.preview('localization_job.create', { projectSlug: a.project.slug, name: 'Guided fixture', targetLocales: ['fr'], workflowPreset: preset }))).result.job;

test('saved choices need confirmation, survive new reads, reject stale previews, mismatched jobs and revoked access', options, async t => {
  const a = await setup(t, 2);
  assert.equal((await flow(a)).next.id, 'context_choice');
  assert(!JSON.stringify(await flow(a)).includes('Hello {name}'), 'Routine flow reads contain no string contents');
  const skip = await configure(a, { contextChoice: 'skip' }), other = await configure(a, { contextChoice: 'enrich' });
  assert.equal((await flow(a)).choices.contextChoice, null);
  assert.equal((await a.request(`/api/agent/proposals/${skip.id}/confirm`, { fingerprint: skip.fingerprint, controllerId: crypto.randomUUID() }, { authorization: `Bearer ${a.token}` })).status, 403);
  await a.confirm(skip); assert.equal((await a.confirm(skip)).replayed, true);
  assert.equal((await flow(a)).next.id, 'workflow_choice');
  assert.equal((await a.request(`/api/agent/proposals/${other.id}/confirm`, { fingerprint: other.fingerprint, controllerId: crypto.randomUUID() })).body.code, 'flow_stale');
  await a.confirm(await configure(a, { workflowPreset: 'ai_only' }));
  assert.equal((await flow(a)).next.id, 'create_job');
  assert.equal(a.meta.calls.length, 0);
  const job = await draft(a, 'ai_only');
  assert.equal((await flow(a)).choices.jobId, job.id);
  assert.equal((await flow(a)).choices.contextChoice, 'skip');
  assert.equal((await flow(a)).next.id, 'translate');
  assert.equal((await a.request('/api/actions/localization_job.create', { projectSlug: a.project.slug, name: 'Contradictory', targetLocales: ['fr'], workflowPreset: 'human_review', steps: ['machine_translation'] })).body.code, 'flow_steps_invalid');
  assert.equal((await a.request('/api/actions/localization_job.update', { jobId: job.id, steps: ['machine_translation', 'review'] })).body.code, 'flow_steps_invalid');
  const f = await flow(a);
  assert.equal((await a.request('/api/actions/localization_flow.configure', { projectSlug: a.project.slug, revision: f.choices.revision, workflowPreset: 'human_review', jobId: job.id })).body.code, 'flow_job_invalid');
  await a.database.query("update source_strings set source_text='New source' where id=$1", [a.sources[0]]);
  assert.equal((await flow(a)).next.id, 'create_job'); assert.equal((await flow(a)).job.stale, true);
  const pending = await configure(a, { contextChoice: 'enrich' });
  const user = (await a.request('/api/me')).body.auth.user.id;
  await a.database.query('update role_assignments set revoked_at=now() where principal_id=$1 and scope_id=$2', [user, a.org]);
  assert.equal((await a.request('/api/actions/localization_flow.get', { projectSlug: a.project.slug })).status, 403);
  for (const p of [pending, skip]) assert.equal((await a.request(`/api/agent/proposals/${p.id}/confirm`, { fingerprint: p.fingerprint, controllerId: crypto.randomUUID() })).status, 403);
});

test('AI findings, user approval and human review are distinct; edits invalidate approval provenance', options, async t => {
  const a = await setup(t, 2);
  await a.confirm(await configure(a, { contextChoice: 'skip', workflowPreset: 'ai_quality' }));
  const job = await draft(a, 'ai_quality');
  await a.confirm(await a.preview('localization_job.start', { jobId: job.id }));
  await a.done(job.id);
  assert.equal((await flow(a)).next.id, 'quality_check');
  const calls = a.meta.calls.length;
  a.meta.control.beforeResponse = ({ body }) => { a.meta.control.text = JSON.stringify({ items: JSON.parse(body.input).items.map(i => ({ id: i.id, verdict: 'pass', issues: [] })) }); };
  const check = await a.preview('localization_job.review', { jobId: job.id, selection: 'all' });
  assert.equal(a.meta.calls.length, calls);
  const run = (await a.confirm(check)).result.qualityRun;
  await eventually(() => flow(a), f => f.next.id === 'quality_approve', 15000);
  assert.equal((await flow(a)).job.coverage.userApproved, 0);
  assert.equal((await flow(a)).job.coverage.humanReviewed, 0);
  const approval = await a.preview('localization_job.verify', { jobId: job.id, runId: run.id });
  assert.equal((await flow(a)).next.id, 'quality_approve');
  await a.confirm(approval);
  assert.equal((await flow(a)).next.id, 'deliver');
  assert.equal((await flow(a)).job.coverage.userApproved, 2);
  assert.equal((await flow(a)).job.coverage.humanReviewed, 0);
  const humanJob = await draft(a, 'human_review');
  assert.equal((await flow(a)).next.id, 'human_review');
  const delivery = await a.request('/api/actions/localization_job.pull_request', { jobId: humanJob.id, connectionId: 'fixture', extractionId: crypto.randomUUID(), baseBranch: 'main', bundlePaths: ['bundle.json'], sourceMapPaths: ['map.json'] });
  assert.equal(delivery.body.code, 'delivery_incomplete', 'AI approval cannot bypass the human workflow’s PR gate');
  // Even a fresh passing AI check on a human workflow cannot mark it reviewed.
  const humanCheck = (await a.confirm(await a.preview('localization_job.review', { jobId: humanJob.id, selection: 'all' }))).result.qualityRun;
  await eventually(async () => (await a.request('/api/actions/localization_job.review_status', { jobId: humanJob.id })).body.result.qualityRun, r => r?.status === 'ready', 15000);
  assert.equal((await a.request('/api/actions/localization_job.verify', { jobId: humanJob.id, runId: humanCheck.id })).body.code, 'review_human_required');
  assert.equal((await a.request(`/api/translations/${a.sources[0]}/fr/approve`, {})).status, 200);
  assert.equal((await flow(a)).next.id, 'human_review');
  assert.equal((await flow(a)).job.coverage.humanReviewed, 1);
  assert.equal((await a.request(`/api/translations/${a.sources[1]}/fr/approve`, {})).status, 200);
  assert.equal((await flow(a)).next.id, 'deliver');
  await a.database.query("update source_strings set source_hash='changed-source' where id=$1", [a.sources[0]]);
  await draft(a, 'human_review');
  assert.equal((await flow(a)).job.coverage.humanReviewed, 1, 'A new source version cannot reuse old human approval');
  await a.database.query("update translations set text='Changed {name}' where source_string_id=$1", [a.sources[0]]);
  assert.equal((await flow(a)).job.coverage.humanReviewed, 1);
  assert.equal((await flow(a)).next.id, 'human_review');
  await draft(a, 'ai_only');
  assert.equal((await flow(a)).next.id, 'deliver', 'AI-only does not require review');
});

test('context generation must be accepted before the guided flow advances; stale guidance is detected', options, async t => {
  const a = await setup(t, 2);
  for (const id of a.sources) await a.database.query("insert into context_variants(source_string_id,file_path,code_context,raw) values($1,'src/greeting.tsx','<h1>Hello {name}</h1>',$2)", [id, { codeEvidence: { text: '<h1>Hello {name}</h1>', startLine: 1, endLine: 1 } }]);
  a.meta.control.beforeResponse = ({ body }) => { a.meta.control.text = JSON.stringify({ items: JSON.parse(body.input).items.map(i => ({ id: i.id, description: 'A personalized greeting heading.', evidence: 'code', confidence: 'high', suggestedMaxCharacters: null, limitReason: 'No fixed width in evidence.' })) }); };
  await a.confirm(await configure(a, { contextChoice: 'enrich' }));
  assert.equal((await flow(a)).next.id, 'context_enrich');
  const run = (await a.confirm(await a.preview('context.enrich', { projectSlug: a.project.slug, allMissing: true }))).result.contextRun;
  await eventually(() => flow(a), f => f.next.id === 'context_accept', 15000);
  assert.equal((await flow(a)).context.currentContext, 0);
  await a.confirm(await a.preview('context.apply', { runId: run.id }));
  assert.equal((await flow(a)).next.id, 'workflow_choice');
  assert.equal((await flow(a)).context.currentContext, 2);
  await a.database.query("update source_strings set purpose='A different screen' where id=$1", [a.sources[0]]);
  assert.equal((await flow(a)).context.needsContext, 1);
  assert.equal((await flow(a)).next.id, 'context_enrich');
  await a.confirm(await configure(a, { contextChoice: 'skip' }));
  assert.equal((await flow(a)).next.id, 'workflow_choice');
  assert.equal(a.meta.calls.length, 1, 'No model calls from polling or saved choices');
});

test('changed quality inputs lead to a fresh check instead of an unusable approval prompt', options, async t => {
  const a = await setup(t, 1);
  await a.confirm(await configure(a, { contextChoice: 'skip', workflowPreset: 'ai_quality' }));
  const job = await draft(a, 'ai_quality');
  await a.confirm(await a.preview('localization_job.start', { jobId: job.id })); await a.done(job.id);
  a.meta.control.beforeResponse = ({ body }) => { a.meta.control.text = JSON.stringify({ items: JSON.parse(body.input).items.map(i => ({ id: i.id, verdict: 'pass', issues: [] })) }); };
  const run = (await a.confirm(await a.preview('localization_job.review', { jobId: job.id, selection: 'all' }))).result.qualityRun;
  await eventually(() => flow(a), f => f.next.id === 'quality_approve', 15000);
  await a.database.query("update prompts set body='Changed guidance' where project_id=$1", [a.project.id]);
  assert.equal((await flow(a)).quality.stale, true);
  assert.equal((await flow(a)).next.id, 'quality_check');
  assert.equal((await a.request('/api/actions/localization_job.verify', { jobId: job.id, runId: run.id })).body.code, 'review_inputs_changed');
});
