import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { localConsole } from '../test-support/local-console.mjs';
import { extractionEngine, seedExtractionProject } from '../test-support/extraction-engine.mjs';

test('extraction has two human approvals, exact project/repository bounds, retry-safe admission and atomic metered import', { skip: process.env.HEDGELING_REQUIRE_AGENT_TEST_DATABASE !== 'true' }, async t => {
  const upstream = await extractionEngine(); t.after(upstream.close);
  const app = await localConsole(process.env.TEST_DATABASE_URL, upstream.env); t.after(app.close);
  const { request, database } = app;
  const p = await seedExtractionProject(database);
  const controllerId = crypto.randomUUID();
  const call = async (name, input) => { const response = await request('/api/actions/' + name, input); assert.equal(response.status, 200, JSON.stringify(response.body)); return response.body.result; };
  const confirm = proposal => request(`/api/agent/proposals/${proposal.id}/confirm`, { fingerprint: proposal.fingerprint, controllerId });
  const input = { projectSlug: p.slug, connectionId: 'test-source', ref: 'main', scanRoots: ['src'] };
  assert.equal((await call('extraction.connections', { projectSlug: p.slug })).connections.length, 1);
  for (const patch of [{ connectionId: 'other' }, { scanRoots: ['src/../secret'] }, { scanRoots: ['src-unrelated'] }]) {
    const result = await request('/api/actions/extraction.start', { ...input, ...patch }); assert([400,403].includes(result.status));
  }
  const proposal = (await call('extraction.start', input)).proposal;
  assert.equal(upstream.jobs.size, 0);
  assert.equal((await request(`/api/agent/proposals/${proposal.id}/confirm`, { fingerprint: 'wrong', controllerId })).status, 409);
  upstream.control.failNextCreate = true;
  assert.equal((await confirm(proposal)).status, 502);
  assert.equal(upstream.jobs.size, 1);
  assert.equal((await database.query('select count(*)::int n from extraction_requests')).rows[0].n, 0);
  const [first, replay] = await Promise.all([confirm(proposal), confirm(proposal)]);
  assert.equal(first.status, 200, JSON.stringify(first.body)); assert.equal(replay.status, 200, JSON.stringify(replay.body));
  assert.equal(upstream.jobs.size, 1);
  assert.equal((await database.query('select count(*)::int n from extraction_requests')).rows[0].n, 1);
  const extractionId = first.body.result.extraction.id;
  const selection = { projectSlug: p.slug, extractionId };
  assert.equal((await call('extraction.get', selection)).extraction.status, 'queued');
  assert.equal((await request('/api/actions/extraction.import', selection)).status, 409);
  const another = (await database.query("insert into projects(slug,name,business_unit_id,source_locale) select 'other-project','Other',business_unit_id,'en-US' from projects where id=$1 returning slug", [p.id])).rows[0];
  assert.equal((await request('/api/actions/extraction.get', { ...selection, projectSlug: another.slug })).status, 404);
  upstream.control.complete = true;
  upstream.control.corruptArtifact = true;
  assert.equal((await request('/api/actions/extraction.import', selection)).status, 422);
  upstream.control.corruptArtifact = false;
  assert.equal((await call('extraction.get', selection)).catalog.total, 2);
  const source = (await database.query("insert into source_strings(project_id,source_hash,source_text) values($1,'hello','Old source') returning id", [p.id])).rows[0];
  await database.query("insert into translations(source_string_id,locale,text,source,human_status) values($1,'fr','Human translation','human','approved')", [source.id]);
  const stale = (await call('extraction.import', selection)).proposal;
  await database.query("insert into source_strings(project_id,source_hash,source_text) values($1,'keep','Keep this source')", [p.id]);
  assert.equal((await confirm(stale)).status, 409);
  const entitlement = (await database.query("select pe.plan_id,pe.limits from plan_entitlements pe join product_plans p on p.id=pe.plan_id where p.key='business-v1' and pe.entitlement_key='state_imports'")).rows[0];
  await database.query("update plan_entitlements set limits=$2 where plan_id=$1 and entitlement_key='state_imports'", [entitlement.plan_id, { resources: { activeSourceStrings: 1 } }]);
  const capped = (await call('extraction.import', selection)).proposal;
  assert.equal((await confirm(capped)).status, 402);
  assert.equal((await database.query('select count(*)::int n from usage_reservations')).rows[0].n, 0);
  assert.equal((await database.query('select count(*)::int n from source_strings')).rows[0].n, 2);
  assert.equal((await database.query('select imported_at from extraction_requests where id=$1', [extractionId])).rows[0].imported_at, null);
  await database.query("update plan_entitlements set limits=$2 where plan_id=$1 and entitlement_key='state_imports'", [entitlement.plan_id, entitlement.limits]);
  const importing = (await call('extraction.import', selection)).proposal;
  assert.deepEqual(importing.preview.resources.catalog, { total: 2, added: 1, updated: 1, unchanged: 0 });
  assert.equal((await database.query("select source_text from source_strings where id=$1", [source.id])).rows[0].source_text, 'Old source');
  const imports = await Promise.all([confirm(importing), confirm(importing)]);
  for (const result of imports) assert.equal(result.status, 200, JSON.stringify(result.body));
  assert.equal((await database.query('select count(*)::int n from source_strings where project_id=$1', [p.id])).rows[0].n, 3);
  assert.equal((await database.query('select text from translations where source_string_id=$1', [source.id])).rows[0].text, 'Human translation');
  assert.equal((await database.query("select count(*)::int n from usage_events where operation='state_import' and outcome='succeeded'")).rows[0].n, 1);
  assert.equal((await database.query("select count(*)::int n from audit_events where action='extraction.import.confirmed'")).rows[0].n, 1);
  assert.equal((await request('/api/actions/extraction.import', selection)).status, 409);
  const denied = (await call('extraction.start', input)).proposal;
  await database.query('update extraction_connections set active=false where project_id=$1', [p.id]);
  assert.equal((await confirm(denied)).status, 403);
  assert.equal((await request('/api/actions/extraction.get', selection)).status, 403);
  assert.equal(upstream.jobs.size, 1);
});
