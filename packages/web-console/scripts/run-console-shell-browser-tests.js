import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { chromium, expect } from "@playwright/test";
import { localConsole } from "../test-support/local-console.mjs";

const app = await localConsole(process.env.TEST_DATABASE_URL || process.argv[2]);
const artifacts = process.env.HEDGELING_NAVIGATION_BROWSER_ARTIFACTS || await fs.mkdtemp(path.join(os.tmpdir(), "hedgeling-navigation-"));
await fs.mkdir(artifacts, { recursive: true });
let browser;
try {
  const executablePath = process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE || process.argv[3];
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: "light" });
  const separator = app.cookie.indexOf("=");
  await context.addCookies([{ name: app.cookie.slice(0, separator), value: app.cookie.slice(separator + 1), url: app.origin, httpOnly: true, sameSite: "Strict" }]);
  await context.addInitScript(() => { localStorage.setItem("hedgeling.agent.mode", "minimized"); });
  const page = await context.newPage();
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(app.origin);
  await expect(page.locator("#adminTab")).toBeVisible();
  await expect(page.locator("#view-home")).toBeVisible();
  await expect(page.locator("#homeProjects")).toContainText("Local project");
  await expect(page.locator("#askAgent")).toBeEnabled();
  const sidebar = page.getByRole("navigation", { name: "Console views", exact: true });
  await page.screenshot({ path: path.join(artifacts, "01-home-light.png") });
  await page.getByRole("button", { name: /Browse projects/ }).click();
  await expect(page.locator("#workspaceRoot")).toContainText("Local project");
  await sidebar.getByRole("button", { name: "Library", exact: true }).click();
  await page.locator("#sectionNav").getByRole("button", { name: "Glossary", exact: true }).click();
  await expect(page.locator("#view-glossary")).toBeVisible();
  await expect(sidebar.getByRole("button", { name: "Library", exact: true })).toHaveAttribute("aria-current", "page");
  await page.goBack(); await expect(page.locator("#view-library")).toBeVisible();
  await page.goForward(); await expect(page.locator("#view-glossary")).toBeVisible();
  await page.reload(); await expect(page.locator("#view-glossary")).toBeVisible();
  await page.locator("#adminTab").click();
  await expect(page.getByRole("heading", { name: "Members", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Business units", exact: true })).toBeHidden();
  await page.locator("#sectionNav").getByRole("button", { name: "Organization", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Business units", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Members", exact: true })).toBeHidden();
  await page.locator("#sectionNav").getByRole("button", { name: "Identity & API", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Enterprise identity", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Enterprise identity", exact: true })).toBeVisible();
  await page.locator("#workspacePicker summary").click();
  await page.locator("#workspaceOptions").getByRole("button", { name: "Local troubleshooting", exact: true }).click();
  await expect(page.locator("#view-access")).toBeVisible();
  await page.screenshot({ path: path.join(artifacts, "02-admin.png") });
  await sidebar.getByRole("button", { name: "My work", exact: true }).click();
  await page.locator("#sectionNav").getByRole("button", { name: "Review", exact: true }).click();
  await expect(page.locator("#view-review #locale")).toBeVisible();
  assert.equal(await page.locator("header.console-topbar #locale").count(), 0);
  await page.locator("#workspacePicker summary").click();
  await page.getByRole("searchbox", { name: "Find a workspace or project" }).fill("local");
  await page.locator("#workspaceOptions").getByRole("button", { name: "Local project", exact: true }).click();
  await expect(page.locator("#workspaceContextLabel")).toHaveText("Local troubleshooting / Default");
  await page.locator("#workspaceTab").click();
  await expect(page.locator("#workspaceRoot")).toContainText("Local project");
  await page.locator("#sidebarCollapse").click();
  await expect(page.locator("body")).toHaveAttribute("data-sidebar-collapsed", "true");
  await page.locator("#sidebarCollapse").click();
  await sidebar.getByRole("button", { name: "Home", exact: true }).click();
  await page.locator("#accountMenu summary").click();
  await page.locator("#accountMenu").getByRole("combobox", { name: "Appearance", exact: true }).selectOption("dark");
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.keyboard.press("Escape");
  await page.screenshot({ path: path.join(artifacts, "03-home-dark.png") });
  await page.locator("#askAgent").click();
  await expect(page.locator("#hedgelingAgent")).toHaveAttribute("data-mode", "panel");
  await page.locator("#agentFollow").check();
  await sidebar.getByRole("button", { name: "Library", exact: true }).click();
  await expect(page.locator("#agentFollow")).not.toBeChecked();
  await expect(page.locator("#view-library")).toBeVisible();
  await page.screenshot({ path: path.join(artifacts, "04-side-panel.png") });
  await page.locator("#hedgelingAgent").getByRole("button", { name: "Full-screen chat", exact: true }).click();
  assert.equal(await page.locator("#consoleSidebar").evaluate((node) => node.inert), true);
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("#consoleSidebar").evaluate((node) => node.inert), false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator("#sidebarToggle").click();
  await expect(sidebar).toBeVisible();
  await sidebar.getByRole("button", { name: "Home", exact: true }).click();
  await expect(page.locator("#view-home")).toBeVisible();
  await expect(page.locator("#consoleSidebar")).toBeHidden();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(artifacts, "05-mobile.png") });
  // An organization can be visible manually but unavailable to delegated chat.
  // Explain the missing role without suggesting a billing upgrade or sending a turn.
  const blockedConfig = (await app.request("/api/agent/config")).body;
  for (const org of blockedConfig.organizations) org.agentAccess = { allowed: false, message: "Hedgeling needs an active organization or project role. Platform-admin access alone does not grant chat access." };
  await page.route("**/api/agent/config", (route) => route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify(blockedConfig) }));
  await page.evaluate(() => sessionStorage.clear());
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await expect(page.locator("#agentScope")).toBeEnabled();
  const chatOrganization = (await app.request("/api/agent/config")).body.organizations[0].id;
  const beforeRuns = (await app.database.query("select count(*)::int as n from agent_runs")).rows[0].n;
  await page.locator("#askAgent").click();
  await page.locator("#agentScope").selectOption(chatOrganization);
  await expect(page.locator("#agentPlanMessage")).toContainText("Platform-admin access alone");
  await expect(page.locator("#agentPlanMessage")).not.toContainText("review the plan");
  await expect(page.locator("#agentUpgrade")).toBeHidden();
  await expect(page.locator("#agentInput")).toBeDisabled();
  assert.equal((await app.database.query("select count(*)::int as n from agent_runs")).rows[0].n, beforeRuns);
  await page.screenshot({ path: path.join(artifacts, "06-chat-role-required.png") });
  await page.locator("#hedgelingAgent").getByRole("button", { name: "Minimize chat", exact: true }).click();
  await page.locator("#workspaceTab").click();
  await expect(page.locator("#workspaceRoot")).toContainText("Local project");
  await page.unroute("**/api/agent/config");
  // Downgrade the isolated fixture's user to project-only translator access.
  // Library remains available; organization administration and hidden routes do not.
  const { id: userId } = (await app.database.query("select id from users where email='developer@hedgeling.example'")).rows[0];
  const { id: projectId } = (await app.database.query("select id from projects where slug='hedgeling-local'")).rows[0];
  await app.database.query("update role_assignments set revoked_at=now() where principal_id=$1", [userId]);
  await app.database.query(`insert into role_assignments(principal_type,principal_id,role_id,scope_type,scope_id)
    select 'user',$1,id,'project',$2 from roles where key='translator' and organization_id is null`, [userId, projectId]);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${app.origin}/#access/identity`);
  await page.reload();
  await expect(page.locator("#view-home")).toBeVisible();
  await expect(page.locator("#adminTab")).toBeHidden();
  await expect(page.locator("#libraryTab")).toBeVisible();
  await expect(page.locator("#paymentOperationsLink")).toBeHidden();
  // Manual navigation also works when the assistant feature is unavailable.
  await page.route("**/api/agent/config", (route) => route.fulfill({ status: 404, contentType: "application/json", body: '{}' }));
  await page.reload();
  await expect(page.locator("#askAgent")).toBeDisabled();
  await page.locator("#workspaceTab").click();
  await expect(page.locator("#workspaceRoot")).toContainText("Local project");
  await page.locator("#workspaceRoot").getByRole("button", { name: /Local project/ }).click();
  await expect(page.locator("#view-review")).toBeVisible();
  assert.deepEqual(errors, []);
  console.log("Console navigation checks passed: actual Home data, Library, Admin sections, history/reload, scoped picker, Review locale, appearance, collapsed sidebar, agent coexistence, manual navigation, mobile drawer, and translator permissions.");
} finally { console.log(`Navigation screenshots: ${artifacts}`); await browser?.close(); await app.close(); }
