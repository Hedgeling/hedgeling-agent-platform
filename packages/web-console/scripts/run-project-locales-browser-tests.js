import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { localConsole } from '../test-support/local-console.mjs';
const app = await localConsole(process.env.TEST_DATABASE_URL);
let browser;
const artifacts = await fs.mkdtemp(path.join(os.tmpdir(), 'hedgeling-locales-browser-'));
try {
  const p = (await app.database.query(`select p.id,p.slug,b.organization_id as org from projects p join business_units b on b.id=p.business_unit_id where p.slug='hedgeling-local'`)).rows[0];
  const account = (await app.database.query('insert into billing_accounts(organization_id) values($1) returning id', [p.org])).rows[0];
  await app.database.query("insert into subscriptions(billing_account_id,plan_id,state) select $1,id,'active' from product_plans where key='business-v1'", [account.id]);
  await app.database.query("update projects set source_locale='en-US' where id=$1", [p.id]);
  await app.database.query('delete from locales where project_id=$1', [p.id]);
  await app.database.query("insert into locales(project_id,locale) values($1,'fr')", [p.id]);
  browser = await chromium.launch({ headless: true, ...(process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE ? { executablePath: process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', reducedMotion: 'reduce' });
  const separator = app.cookie.indexOf('=');
  await context.addCookies([{ name: app.cookie.slice(0, separator), value: app.cookie.slice(separator + 1), url: app.origin, httpOnly: true, sameSite: 'Strict' }]);
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message)); page.setDefaultTimeout(15000);
  await page.goto(app.origin);
  const chat = page.locator('#hedgelingAgent');
  await chat.locator('#agentScope').selectOption({ label: 'Local troubleshooting' });
  await chat.getByRole('button', { name: 'Minimize chat', exact: true }).click();
  await page.evaluate(() => window.HedgelingConsole.openWorkspace());
  const panel = page.locator('.project-languages');
  await expect(panel.locator('.project-language-source')).toContainText('en-US');
  await panel.locator('summary').click();
  await panel.getByLabel('Languages to add', { exact: true }).fill('fr-CA, ja');
  await panel.getByRole('button', { name: 'Review languages', exact: true }).click();
  const review = panel.locator('.workspace-confirmation');
  await expect(review).toContainText('fr-CA, ja'); await expect(review).not.toContainText('tell me');
  assert.equal((await app.database.query('select count(*)::int n from locales where enabled')).rows[0].n, 1);
  await page.screenshot({ path: path.join(artifacts, '01-manual-language-approval.png') });
  await review.getByRole('button', { name: 'Edit details', exact: true }).click();
  await expect(panel.getByLabel('Languages to add', { exact: true })).toHaveValue('fr-CA, ja');
  await panel.getByRole('button', { name: 'Review languages', exact: true }).click();
  await review.getByRole('button', { name: 'Add target languages', exact: true }).click();
  await expect(panel.locator('.project-language-status')).toContainText('Added fr-CA, ja');
  await expect(page.locator('#locale option[value="ja"]')).toHaveCount(1);
  await page.evaluate(() => window.HedgelingConsole.openProject('hedgeling-local'));
  await page.getByRole('button', { name: 'Manage project languages', exact: true }).click();
  await expect(panel.getByLabel('Languages to add', { exact: true })).toBeFocused();
  await panel.getByLabel('Languages to add', { exact: true }).fill('en_US');
  await panel.getByRole('button', { name: 'Review languages', exact: true }).click();
  await expect(panel.locator('.agent-error')).toContainText('source language');
  await panel.getByLabel('Languages to add', { exact: true }).fill('');
  await page.getByRole('button', { name: 'Open Hedgeling assistant' }).click();
  await chat.locator('#agentFollow').check();
  await chat.locator('#agentInput').fill('Add locales "de" to project "hedgeling-local".');
  await chat.getByRole('button', { name: 'Send message', exact: true }).click();
  const approval = chat.locator('.agent-proposal').getByRole('button', { name: 'Add target languages', exact: true });
  await expect(approval).toBeEnabled();
  await expect(panel.locator('summary')).toHaveAttribute('data-agent-attention', 'approval');
  await page.screenshot({ path: path.join(artifacts, '02-chat-language-approval.png') });
  await approval.click();
  await expect(chat).toContainText('Added de to your project after confirmation.');
  await chat.getByRole('button', { name: 'Minimize chat', exact: true }).click();
  await expect(panel.locator('.project-language-targets')).toContainText('German');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => { const select = document.querySelector('[data-theme-preference]'); select.value = 'dark'; select.dispatchEvent(new Event('change', { bubbles: true })); });
  await panel.locator('summary').click();
  await panel.getByLabel('Languages to add', { exact: true }).fill('uk');
  await panel.getByRole('button', { name: 'Review languages', exact: true }).click();
  await review.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(artifacts, '03-mobile-language-approval.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await review.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal((await app.database.query("select count(*)::int n from locales where locale='uk'")).rows[0].n, 0);
  assert.deepEqual(errors, []);
  console.log('Project languages browser checks passed: manual review/edit/save/cancel, translation selector, shortcut, agent/MCP approval and highlight, mobile. Screenshots: ' + artifacts);
} finally { await browser?.close(); await app.close(); }
