import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { localConsole } from '../test-support/local-console.mjs';
import { extractionEngine, seedExtractionProject } from '../test-support/extraction-engine.mjs';

const upstream = await extractionEngine();
let app, browser;
const artifacts = await fs.mkdtemp(path.join(os.tmpdir(), 'hedgeling-extraction-browser-'));
try {
  app = await localConsole(process.env.TEST_DATABASE_URL, upstream.env);
  await seedExtractionProject(app.database);
  browser = await chromium.launch({ headless: true, ...(process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE ? { executablePath: process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', reducedMotion: 'reduce' });
  const separator = app.cookie.indexOf('=');
  await context.addCookies([{ name: app.cookie.slice(0, separator), value: app.cookie.slice(separator + 1), url: app.origin, httpOnly: true, sameSite: 'Strict' }]);
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(app.origin);
  const chat = page.locator('#hedgelingAgent');
  await expect(chat).toBeVisible();
  await chat.locator('#agentScope').selectOption({ label: 'Local troubleshooting' });
  await chat.locator('#agentInput').fill('Extract source from project "hedgeling-local" at "main" in "src".');
  await chat.getByRole('button', { name: 'Send message', exact: true }).click();
  const approval = chat.locator('.agent-proposal');
  await expect(approval.getByRole('button', { name: 'Start extraction', exact: true })).toBeEnabled({ timeout: 15000 });
  await expect(approval).toContainText('Synthetic/source'); await expect(approval).toContainText('private hosted');
  assert.equal(upstream.jobs.size, 0);
  await page.screenshot({ path: path.join(artifacts, '01-chat-extraction-approval.png') });
  await approval.getByRole('button', { name: 'Start extraction', exact: true }).click();
  await expect(chat.locator('.extraction-progress')).toContainText('Hedgeling is reading your source', { timeout: 15000 });
  upstream.control.complete = true;
  await chat.locator('.extraction-progress').getByRole('button', { name: 'Refresh status' }).click();
  await expect(chat.locator('.extraction-progress')).toContainText('Your strings are ready to review');
  // Status-card refresh can finish before the post-confirmation agent turn.
  // Wait for server readiness as well as the composer before sending a new turn.
  await expect.poll(async () => (await app.database.query('select status from agent_runs order by created_at desc limit 1')).rows[0]?.status, { timeout: 15000 }).toBe('awaiting_input');
  await expect(chat.locator('#agentInput')).toBeEnabled({ timeout: 15000 });
  await chat.locator('.extraction-progress').getByRole('button', { name: 'Review import' }).click();
  await expect(chat.locator('.agent-proposal').getByRole('button', { name: 'Import source strings', exact: true })).toBeEnabled({ timeout: 15000 });
  assert.equal((await app.database.query('select count(*)::int n from source_strings')).rows[0].n, 0);
  await page.screenshot({ path: path.join(artifacts, '02-chat-import-approval.png') });
  await chat.locator('.agent-proposal').getByRole('button', { name: 'Import source strings', exact: true }).click();
  await expect(chat).toContainText('Your extracted source strings have been imported', { timeout: 15000 });
  await expect(chat.locator('.extraction-progress')).toContainText('Source strings imported');
  await expect(chat.locator('.extraction-progress').getByRole('button', { name: 'Review import' })).toHaveCount(0);
  assert.equal((await app.database.query('select count(*)::int n from source_strings')).rows[0].n, 2);
  await expect(chat.locator('#agentInput')).toBeEnabled({ timeout: 15000 });
  await chat.getByRole('button', { name: 'Minimize chat', exact: true }).click();
  await page.evaluate(() => window.HedgelingConsole.openWorkspace());
  const panel = page.locator('.extraction-panel');
  await panel.locator('summary').click();
  await expect(panel.getByRole('button', { name: 'Review extraction', exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Review extraction', exact: true }).click();
  await expect(panel.locator('.workspace-confirmation')).toContainText('Review this step');
  await expect(panel.locator('.workspace-confirmation')).not.toContainText('tell me');
  await page.screenshot({ path: path.join(artifacts, '03-manual-approval.png') });
  await panel.locator('.workspace-confirmation').getByRole('button', { name: 'Edit details', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Review extraction', exact: true })).toBeVisible();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: path.join(artifacts, '04-progress.png') });
  assert.deepEqual(errors, []);
  console.log('Chat/MCP and manual extraction browser flows passed. Screenshots: ' + artifacts);
} finally { await browser?.close(); await app?.close(); await upstream.close(); }
