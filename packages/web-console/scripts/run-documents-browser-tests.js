import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { setupTranslationJobs } from '../test-support/translation-jobs.mjs';
import { eventually } from '../test-support/local-console.mjs';
const cleanup = [], app = await setupTranslationJobs({ after: fn => cleanup.push(fn) }, 1);
const artifacts = await fs.mkdtemp(path.join(os.tmpdir(), 'hedgeling-documents-browser-'));
let browser, page;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE ? { executablePath: process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', reducedMotion: 'reduce' });
  const split = app.cookie.indexOf('=');
  await context.addCookies([{ name: app.cookie.slice(0, split), value: app.cookie.slice(split + 1), url: app.origin, httpOnly: true, sameSite: 'Strict' }]);
  page = await context.newPage(); page.setDefaultTimeout(15000); const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(app.origin);
  const chat = page.locator('#hedgelingAgent');
  await chat.locator('#agentScope').selectOption({ label: 'Local troubleshooting' });
  await expect(chat.locator('#agentInput')).toBeEnabled();
  await chat.getByRole('button', { name: 'Minimize chat', exact: true }).click();
  await page.evaluate(async org => { await window.HedgelingAgent.browseWorkspace(org); window.HedgelingConsole.openWorkspace(); }, app.org);
  const panel = page.locator(`.document-panel[data-project-slug="${app.project.slug}"]`);
  await panel.locator('summary').first().click();
  await panel.getByLabel('Document', { exact: true }).setInputFiles({ name: 'welcome.md', mimeType: 'text/markdown', buffer: Buffer.from('Hello {name}\n\nWelcome {name}') });
  await panel.getByRole('button', { name: 'Upload and inspect', exact: true }).click();
  await expect(panel.locator('.document-preview')).toContainText('2 text sections');
  await panel.getByLabel('fr', { exact: true }).check();
  await panel.getByRole('button', { name: 'Review document job', exact: true }).click();
  const preview = panel.locator('.workspace-confirmation');
  await expect(preview).toContainText('only those sections'); assert.equal(app.meta.calls.length, 0);
  await preview.scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(artifacts, '01-document-approval.png') });
  await preview.getByRole('button', { name: 'Import document and create job', exact: true }).click();
  const job = await eventually(async () => (await app.database.query('select id from localization_jobs where source_document_id is not null')).rows[0], Boolean);
  const row = page.locator(`[data-resource-type="job"][data-resource-id="${job.id}"]`);
  await row.getByRole('button', { name: 'Preview translation start', exact: true }).click();
  await row.locator('.workspace-confirmation').getByRole('button', { name: 'Start translation', exact: true }).click();
  await expect(row.getByRole('region', { name: 'Translation job progress', exact: true })).toContainText('Drafts ready for review', { timeout: 20000 });
  await row.locator('.document-export summary').click();
  await row.getByLabel('Translation status', { exact: true }).selectOption('drafts');
  await row.getByLabel('Format', { exact: true }).selectOption('csv');
  await row.getByRole('button', { name: 'Prepare download', exact: true }).click();
  const downloadPromise = page.waitForEvent('download'); await row.getByRole('button', { name: 'Download', exact: true }).click();
  const download = await downloadPromise; assert.match(await fs.readFile(await download.path(), 'utf8'), /Bonjour/);
  await page.screenshot({ path: path.join(artifacts, '02-document-download.png') });
  await page.evaluate(() => window.HedgelingAgent.open());
  await chat.getByRole('button', { name: 'Upload document' }).click();
  const dialog = page.getByRole('dialog'); await expect(dialog).toBeVisible();
  await dialog.getByLabel('Project for this document').selectOption(app.project.slug);
  await dialog.getByLabel('Document', { exact: true }).setInputFiles({ name: 'chat.md', mimeType: 'text/markdown', buffer: Buffer.from('Hello {name}') });
  await dialog.getByRole('button', { name: 'Upload and inspect', exact: true }).click();
  await dialog.getByRole('button', { name: 'Discuss this document in chat', exact: true }).click();
  await expect(chat.locator('#agentInput')).toHaveValue(/Please inspect uploaded document/);
  const docId = (await app.database.query("select id from uploaded_documents where filename='chat.md'")).rows[0].id;
  await chat.locator('#agentInput').fill(`Create a French document job for ${docId}`);
  await chat.getByRole('button', { name: 'Send message', exact: true }).click();
  const card = chat.locator('.agent-proposal').filter({ hasText: 'Import document and create job' });
  await expect(card.getByRole('button', { name: 'Import document and create job', exact: true })).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 }); await card.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(artifacts, '03-mobile-chat-document.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.emulateMedia({ colorScheme: 'dark' }); await page.screenshot({ path: path.join(artifacts, '04-dark-chat-document.png') });
  assert.deepEqual(errors, []); console.log('Document browser flow passed. Artifacts: ' + artifacts);
} catch(e) { await page?.screenshot({ path: path.join(artifacts, 'failure.png') }); console.error('Artifacts: ' + artifacts); throw e; }
finally { await browser?.close(); for (const close of cleanup.reverse()) await close(); }
