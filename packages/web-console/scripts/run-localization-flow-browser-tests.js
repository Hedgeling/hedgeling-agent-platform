import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { setupTranslationJobs } from '../test-support/translation-jobs.mjs';
const cleanup = [], app = await setupTranslationJobs({ after: fn => cleanup.push(fn) }, 2);
const artifacts = await fs.mkdtemp(path.join(os.tmpdir(), 'hedgeling-guided-flow-'));
let browser, page;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE ? { executablePath: process.env.HEDGELING_E2E_CHROMIUM_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const split = app.cookie.indexOf('=');
  await context.addCookies([{ name: app.cookie.slice(0, split), value: app.cookie.slice(split + 1), url: app.origin, httpOnly: true, sameSite: 'Strict' }]);
  page = await context.newPage(); page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(app.origin);
  const chat = page.locator('#hedgelingAgent');
  await chat.locator('#agentScope').selectOption({ label: 'Local troubleshooting' });
  await expect(chat.locator('#agentInput')).toBeEnabled();
  await chat.getByRole('button', { name: 'Minimize chat', exact: true }).click();
  const open = async () => {
    await page.waitForFunction(() => Boolean(window.HedgelingAgent?.browseWorkspace));
    await page.evaluate(async org => { await window.HedgelingAgent.browseWorkspace(org); window.HedgelingConsole.openWorkspace(); }, app.org);
    await page.getByRole('button', { name: 'Open business unit: Default', exact: true }).click();
  };
  await open();
  const flow = page.locator(`#workspaceRoot [data-flow-project="${app.project.slug}"]`);
  await expect(flow).toHaveAttribute('data-flow-step', 'context_choice');
  await flow.getByRole('button', { name: 'Continue with existing context', exact: true }).click();
  await expect(flow.locator('.workspace-confirmation')).toContainText('No model requests');
  assert.equal(app.meta.calls.length, 0);
  await flow.locator('.workspace-confirmation').getByRole('button', { name: 'Save workflow choices', exact: true }).click();
  await expect(flow).toHaveAttribute('data-flow-step', 'workflow_choice');
  await flow.getByRole('button', { name: 'AI translation + quality check', exact: true }).click();
  await flow.locator('.workspace-confirmation').getByRole('button', { name: 'Save workflow choices', exact: true }).click();
  await expect(flow).toHaveAttribute('data-flow-step', 'create_job');
  await page.reload(); await open();
  await expect(flow).toHaveAttribute('data-flow-step', 'create_job');
  await expect(flow).toContainText('Enrichment skipped');
  await flow.getByRole('button', { name: 'Preview job draft', exact: true }).click();
  await flow.locator('.workspace-confirmation').getByRole('button', { name: 'Create job draft', exact: true }).click();
  await expect(flow).toHaveAttribute('data-flow-step', 'translate');
  assert.equal(app.meta.calls.length, 0);
  await flow.getByRole('button', { name: 'Preview translation start', exact: true }).click();
  await flow.locator('.workspace-confirmation').getByRole('button', { name: 'Start translation', exact: true }).click();
  await expect(flow).toHaveAttribute('data-flow-step', 'quality_check', { timeout: 20000 });
  app.meta.control.beforeResponse = ({ body }) => { app.meta.control.text = JSON.stringify({ items: JSON.parse(body.input).items.map(i => ({ id: i.id, verdict: 'pass', issues: [] })) }); };
  await flow.getByRole('button', { name: 'Preview AI quality check', exact: true }).click();
  await flow.locator('.workspace-confirmation').getByRole('button', { name: 'Run AI quality check', exact: true }).click();
  await expect(flow).toHaveAttribute('data-flow-step', 'quality_approve', { timeout: 20000 });
  await expect(flow).toContainText('0 approved after AI assessment');
  await page.screenshot({ path: path.join(artifacts, '01-guided-approval.png') });
  await flow.getByRole('button', { name: 'Preview approval of passing results', exact: true }).click();
  await flow.locator('.workspace-confirmation').getByRole('button', { name: 'Verify passing translations', exact: true }).click();
  await expect(flow).toHaveAttribute('data-flow-step', 'deliver');
  await expect(flow).toContainText('2 approved after AI assessment · 0 human reviewed');
  await flow.getByRole('button', { name: 'Open PR delivery', exact: true }).click();
  const delivery = page.locator('.job-delivery[open]');
  await expect(delivery).toContainText('Connect a repository to this project first.');
  // A new chat resolves the saved flow through the real MCP tool and event stream.
  await page.evaluate(() => window.HedgelingAgent.open());
  await chat.getByRole('button', { name: 'New chat', exact: true }).click();
  await chat.locator('#agentScope').selectOption({ label: 'Local troubleshooting' });
  await chat.locator('#agentInput').fill(`Show localization flow for ${app.project.slug}`);
  await chat.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(chat.locator(`[data-flow-project="${app.project.slug}"]`)).toHaveAttribute('data-flow-step', 'deliver');
  await expect(chat.locator(`[data-flow-project="${app.project.slug}"]`)).toContainText('Enrichment skipped');
  await chat.getByRole('button', { name: 'Minimize chat', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 }); await flow.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(artifacts, '02-guided-mobile.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(app.meta.calls.length, 3);
  assert.deepEqual(errors, []);
  console.log(`Guided localization browser flow passed. Artifacts: ${artifacts}`);
} catch (error) { await page?.screenshot({ path: path.join(artifacts, 'failure.png') }); console.error(`Artifacts: ${artifacts}`); throw error; }
finally { await browser?.close(); for (const close of cleanup.reverse()) await close(); }
